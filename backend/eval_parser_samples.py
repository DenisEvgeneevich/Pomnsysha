def load_ai_module():
    root = pathlib.Path.cwd()
    mod_path = root / 'backend' / 'ai.py'
    spec = importlib.util.spec_from_file_location('ai_module', str(mod_path))
    ai = importlib.util.module_from_spec(spec)
    loader = spec.loader
    loader.exec_module(ai)
    return ai


