def run(samples):
    ai = load_ai_module()
    total = len(samples)
    ok = 0
    results = []
    for s in samples:
        res = ai.extract_task_via_gigachat(s)
        success = bool(res.get('success') and res.get('processed_task'))
        if success:
            ok += 1
        results.append({'text': s, 'success': success, 'result': res})

    print(f"Processed {total} samples, parsed as tasks: {ok} (rate: {ok/total:.2%})")
    for r in results:
        pprint(r)


if __name__ == '__main__':
    run(SAMPLES)
